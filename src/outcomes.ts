export function describeOutcome(before:State,after:State,event:Event,c:Choice,success:boolean):string{
  const passive=!c.effects&&!c.flags&&!c.career&&!c.familyStatus&&!c.risks&&!c.retired&&c.base===100;
  if(passive)return '今回は暮らしを変えず、いつもの日々を続けることにした。';
  let text=(success?c.success:c.failure)??scenes[event.id]?.[success?0:1]??(success?'話し合いを終え、選んだ方針で次の日を迎えた。':'話はまとまらず、その日は帰って今後を考えた。');
  if(before.career!==after.career)text+=` 職業は${after.career}になった。`;
  if(before.country!==after.country)text+=` ${after.country}での暮らしが始まった。`;
  if(before.familyStatus!==after.familyStatus&&event.id==='divorce')text+=after.familyStatus==='divorced'?' 離婚が成立し、別々の暮らしが始まった。':'';
  if(!before.flags.includes('imprisoned')&&after.flags.includes('imprisoned'))text+=' 説明は受け入れられず、拘束された。';
  const delta=assetValue(after.stats.wealth)-assetValue(before.stats.wealth);
  if(delta)text+=` 推定資産は${formatMoney(Math.abs(delta))}${delta>0?'増えた':'減った'}。`;
  if(after.stats.health<before.stats.health)text+=' 疲れが残り、体調を崩した。';
  return text;
}
